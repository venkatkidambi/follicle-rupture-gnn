function figureHandle = plot_tuning_comparison(fitFile)
%PLOT_TUNING_COMPARISON Measured and independently simulated trajectories.
repo=fileparts(mfilename('fullpath'));
if nargin<1, fitFile=fullfile(repo,'results','parameter_tuning','best_fit.mat'); end
loaded=load(fitFile,'fit'); fit=loaded.fit; data=fit.data;
figureHandle=figure('Color','w','Visible','off','Position',[100 100 1450 820]);
layout=tiledlayout(2,3,'TileSpacing','compact','Padding','compact');
for band=1:3
    nexttile;
    mask=data.bandMasks(:,band);
    plot(data.time/60,mean(fit.metrics.observedAxial(mask,:),1)*1e6,'ko-', ...
        'MarkerSize',3,'LineWidth',1.2); hold on;
    plot(data.time/60,mean(fit.metrics.predictedAxial(mask,:),1)*1e6, ...
        'Color',[.05 .4 .8],'LineWidth',2);
    yline(0,':','Color',[.7 .7 .7]); grid on;
    title(sprintf('Initial %d-%d%% band',data.percentileRanges(band,:)));
    xlabel('Time (min)'); ylabel('Mean axial displacement (\mum)');
    legend('Tracked cells, pose corrected','Tuned force model', ...
        'Location','northwest');
end
nexttile;
mask=data.validationNodes;
plot(data.time/60,sqrt(mean(fit.metrics.error_um(mask,:).^2,1)), ...
    'Color',[.05 .4 .8],'LineWidth',2); hold on;
plot(data.time/60,sqrt(mean(fit.stationaryMetrics.error_um(mask,:).^2,1)), ...
    'k--','LineWidth',1.2);
scatter(data.time(data.validationFrames)/60, ...
    sqrt(mean(fit.metrics.error_um(mask,data.validationFrames).^2,1)),25, ...
    [.05 .4 .8],'filled');
grid on; xlabel('Time (min)'); ylabel('3D position RMSE (\mum)');
title('Cells excluded from fitting');
legend('Tuned model','No-motion benchmark','Held-out frames','Location','northwest');
nexttile;
initial=fit.param.nodeCoords*1e6;
prediction=initial+reshape(fit.prediction.Y(end,:),3,[]).'*1e6;
observed=data.position(:,:,end)*1e6;
scatter(initial(:,1),initial(:,2),9,[.7 .7 .7],'filled'); hold on;
scatter(observed(:,1),observed(:,2),12,[.1 .1 .1]);
scatter(prediction(:,1),prediction(:,2),12,[.05 .4 .8]);
axis equal; grid on; xlabel('x (\mum)'); ylabel('y (\mum)');
title('Final positions, projection onto initial xy plane');
legend('Initial','Experiment','Tuned model','Location','best');
nexttile; axis off;
summary=sprintf(['%d tracked cells; %d frames over %.0f min\n' ...
    'Uniform frame interval: %.4f s\n\n' ...
    'Training 3D RMSE: %.2f µm\n' ...
    'Held-out 3D RMSE: %.2f µm\n' ...
    'No-motion held-out RMSE: %.2f µm\n' ...
    'Original model held-out RMSE: %.2f µm\n\n' ...
    'Held out: %d cells and %d interleaved frames\n' ...
    'Pose correction: rigid fit to training far-cap cells\n' ...
    'Same specimen; not independent biological validation\n\n' ...
    'No prescribed node displacements\n' ...
    'One global natural-length contraction program\n' ...
    'Spring force scale remains an assumption'], ...
    size(data.position,1),numel(data.time),data.time(end)/60, ...
    data.frameInterval,fit.metrics.trainRMSE_um,fit.metrics.validationRMSE_um, ...
    fit.stationaryMetrics.validationRMSE_um,fit.baselineMetrics.validationRMSE_um, ...
    nnz(data.validationNodes),nnz(data.validationFrames));
text(0,1,summary,'Units','normalized','VerticalAlignment','top','FontSize',11,'Interpreter','none');
title(layout,'Experimental trajectories and force-driven parameter fit');
exportgraphics(figureHandle,fullfile(fileparts(fitFile),'trajectory_comparison.png'),'Resolution',180);
end
